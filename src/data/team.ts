/** Short label under a therapist's name, e.g. "Belváros" or "Belváros és Buda". */
export const clinicLabel = (name: string) => (locationOf[name] ?? []).map((id) => CLINIC_SHORT[id]).join(' és ');


/** Passed the McKenzie Institute International credentialing exam (Cert. MDT level). */
export const credentialed = terapeutak.filter((t) => !t.status && t.quals.some((q) => /minősítővizsga/i.test(q)));

// Plain-language focus areas derived from each therapist's own qualification list,
// so patients can choose without decoding course names. Order = priority shown on the card.
const FOCUS: [RegExp, string][] = [
  [/Schroth/i, 'gerincferdülés'],
  [/Sportrehab|Sportsérül|TRX/i, 'sportsérülések'],
  [/Műtét utáni|Ortopédiai rehab/i, 'műtét utáni rehabilitáció'],
  [/Inkontinencia|Gátizom|Szülés utáni|Kismama/i, 'szülés utáni és női panaszok'],
  [/Állkapocs/i, 'állkapocsízület'],
  [/Neurológiai/i, 'neurológiai rehabilitáció'],
  [/Gyermek/i, 'gyermekek'],
  [/Lymphoedema/i, 'nyiroködéma'],
  [/Geriátri/i, 'idősek gyógytornája'],
  [/Manuálterápi|Maitland|Mulligan/i, 'manuálterápia'],
];

export const focusAreas = (t: Therapist): string[] => {
  const found = FOCUS.filter(([re]) => t.quals.some((q) => re.test(q))).map(([, label]) => label);
  return ['derék- és nyakfájás', ...found].slice(0, 3);
};
